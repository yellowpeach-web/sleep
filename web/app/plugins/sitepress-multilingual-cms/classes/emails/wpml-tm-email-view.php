<?php

abstract class WPML_TM_Email_View {

	const FOOTER_TEMPLATE = 'email-footer.twig';
	const HEADER_TEMPLATE = 'email-header.twig';

	protected $template_service;

	public function __construct( WPML_Twig_Template $template_service ) {
		$this->template_service = $template_service;
	}

	public function render_header( $username = '' ) {
		$model = array(
			/* translators: Formal greeting at the top of an email WPML sends. %s: the name of the person the email goes to. */
			'greetings' => sprintf( __( 'Dear %s,', 'sitepress' ), $username ),
		);

		return $this->template_service->show( $model, self::HEADER_TEMPLATE );
	}

	public function render_casual_header( $first_name = '' ) {
		$model = array(
			/* translators: Friendly greeting at the top of an email WPML sends. %s: the first name of the person the email goes to. */
			'greetings' => sprintf( __( 'Hi %s,', 'sitepress' ), $first_name ),
		);

		return $this->template_service->show( $model, self::HEADER_TEMPLATE );
	}

	protected function render_email_footer( $bottom_text = '' ) {
		$site_url = get_bloginfo( 'url' );

		$model = array(
			'bottom_text' => $bottom_text,
			'wpml_footer' => sprintf(
				/* translators: %s: link to the site. */
				esc_html__( 'Generated by WPML plugin, running on %s.', 'sitepress' ),
				'<a href="' . $site_url . '" style="color: #ffffff;">' . $site_url . '</a>'
			),
		);

		return $this->template_service->show( $model, self::FOOTER_TEMPLATE );
	}

	protected function render_notification_settings_footer() {
		$notifications_url  = esc_url( admin_url( 'admin.php?page=' . WPML_TM_FOLDER . WPML_Translation_Management::PAGE_SLUG_SETTINGS . '&section=translators&flash=translation-notifications' ) );
		$notifications_text = esc_html__( 'WPML Notification Settings', 'sitepress' );
		$notifications_link = '<a href="' . $notifications_url . '" style="color: #ffffff;">' . $notifications_text . '</a>';

		$bottom_text = sprintf(
			/* translators: Last line of the email WPML sends about translation work. %s: a link, already wrapped in its tags, that opens the site. */
			esc_html__(
				'To stop receiving notifications, log-in to %s and change your preferences.',
				'sitepress'
			),
			$notifications_link
		);

		return $this->render_email_footer( $bottom_text );
	}
}
